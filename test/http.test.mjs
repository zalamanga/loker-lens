import test from 'node:test';
import assert from 'node:assert/strict';
import * as fs from 'node:fs/promises';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { createServer } from '../server.js';
import { readConfiguration } from '../lib/config.mjs';
import { SafeCache } from '../lib/cache.mjs';
import { snapshotDecoder } from '../lib/snapshot.mjs';
import { createApplication } from '../lib/application.mjs';
import { validateStatus } from '../public/model.mjs';

test('actual loopback HTTP isolates private files and origins, saves the demo, replays once and exposes its real source preview', async (t) => {
  const parent = path.resolve('.test-cache'); await fs.mkdir(parent, { recursive: true });
  const directory = await fs.mkdtemp(path.join(parent, 'http-contract-'));
  const config = readConfiguration(process.cwd(), { LOKER_DATA_DIR: directory });
  const store = await SafeCache.open(directory, snapshotDecoder('demo'));
  const application = createApplication({ config, store }); const server = createServer({ application });
  t.after(async () => {
    await new Promise((resolve) => { server.close(resolve); server.closeAllConnections(); });
    await application.close();
    const target = path.resolve(directory);
    assert.equal(path.dirname(target), parent); assert.ok(path.basename(target).startsWith('http-contract-'));
    assert.equal((await fs.realpath(target)).toLowerCase(), target.toLowerCase());
    await fs.rm(target, { recursive: true });
  });
  await new Promise((resolve, reject) => { server.once('error', reject); server.listen(0, '127.0.0.1', resolve); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const call = (route, options) => fetch(`${base}${route}`, options);
  const post = (route, body, headers = {}) => call(route, { method: 'POST', headers: { origin: base, 'content-type': 'application/json', ...headers }, body: JSON.stringify(body) });
  assert.equal((await call('/api/health')).status, 200);
  const initial = await (await call('/api/state')).json(); validateStatus(initial, true); assert.equal(initial.snapshot, null);
  for (const route of ['/server.js', '/lib/cache.mjs', '/.data/jobs.json', '/test/http.test.mjs', '/package.json', '/unknown']) assert.equal((await call(route)).status, 404, route);
  assert.equal((await call('/api/status?operationId=no')).status, 400);
  assert.equal((await call('/api/state?unexpected=1')).status, 400);
  const input = { operationId: randomUUID(), expectedGeneration: null, replaceDamagedDigest: null };
  assert.equal((await post('/api/sync', input, { origin: 'https://outside.invalid' })).status, 403);
  assert.equal((await post('/api/sync', input, { 'sec-fetch-site': 'cross-site' })).status, 403);
  assert.equal((await post('/api/sync', { ...input, extra: true })).status, 422);
  assert.equal((await post('/api/sync', input, { 'content-type': 'text/plain' })).status, 415);
  assert.equal((await post('/api/sync', { value: 'x'.repeat(2100) })).status, 413);
  assert.equal((await call('/api/sync', { method: 'PUT', headers: { origin: base } })).status, 405);
  assert.equal((await post('/api/sync', input)).status, 202); await application.waitForIdle();
  const result = await call('/api/state'); const data = await result.json(); validateStatus(data, true);
  assert.equal(data.snapshot.jobs.length, 24); assert.equal(data.generation, input.operationId);
  assert.equal(result.headers.get('cache-control'), 'no-store'); assert.ok(result.headers.get('content-security-policy').includes("frame-ancestors 'none'"));
  const rawBefore = await fs.readFile(path.join(directory, 'jobs.json'));
  const replay = await (await post('/api/sync', input)).json(); assert.equal(replay.replay, true);
  assert.deepEqual(await fs.readFile(path.join(directory, 'jobs.json')), rawBefore);
  const preview = await call(data.snapshot.jobs[0].url); assert.equal(preview.status, 200); assert.match(await preview.text(), /contoh rekaan/i);
  assert.equal((await call('/demo/source/99999')).status, 404);
});
